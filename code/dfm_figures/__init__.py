"""Figure generation for the DFM study from the released result files.

Each module defines its presentation settings at module level (figure size, fonts, colors,
axis limits, legend placement) and a ``build()`` function that reads the released data and
returns the Matplotlib figure. The two schematic figures of the paper (the hybrid AC/DC test
network and the DFM framework diagram) are author-created artwork and are supplied as final
files in ``figures/``; they are not generated by code.
"""
from importlib import import_module

FIGURES = {
    "Fig_operating_profiles": "operating_profiles",
    "Fig_flexibility_evolution": "flexibility_evolution",
    "Fig_energy_performance": "energy_performance",
    "Fig_network_security": "network_security",
    "Fig_monte_carlo": "monte_carlo",
    "Fig_uncertainty_reserve": "uncertainty_reserve",
    "Fig_ablation_sensitivity": "ablation_sensitivity",
    # supporting figures (not in the paper)
    "Fig_flexibility_limits": "flexibility_limits",
    "Fig_degradation_model": "degradation_model",
}

AUTHOR_ARTWORK = ("Fig_topology3_dfm", "Fig_dfm_framework")


def build(name):
    """Return the Matplotlib figure ``name`` (a key of FIGURES)."""
    return import_module(f".{FIGURES[name]}", __name__).build()
